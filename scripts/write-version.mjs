// Writes src/app/version.generated.ts with the short git commit hash and the
// build time, so the running app can show which build it is. Runs before
// `ng build`, `ng serve` and `ng test` through the npm pre-hooks; the output
// is not committed.
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

function commit() {
  try {
    return execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] })
      .toString()
      .trim();
  } catch {
    return (process.env.GITHUB_SHA ?? 'dev').slice(0, 7);
  }
}

const version = { commit: commit(), builtAt: new Date().toISOString() };
const source = `// Generated by scripts/write-version.mjs. Do not edit.
export const APP_VERSION = ${JSON.stringify(version, null, 2)} as const;
`;
writeFileSync(new URL('../src/app/version.generated.ts', import.meta.url), source);
console.log(`version ${version.commit}`);
